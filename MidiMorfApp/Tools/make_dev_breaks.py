#!/usr/bin/env python3
"""Embed test breaks into Debug builds only.

Writes MidiMorfApp/Source/DevBreaks.h, which is git-ignored and compiled
only when JUCE_DEBUG is set (see BreakLibrary.h). Use it for loops you can
test with on your own phone but can't ship: they never reach a Release /
TestFlight / App Store build and never land in the repo.

    make_dev_breaks.py "Name" path/to/loop.wav BARS BPM [...more triples]

Each loop is trimmed to exactly BARS bars at BPM from its start.
"""
import io, os, sys, wave

def trimmed_wav(path, bars, bpm):
    with wave.open(path, 'rb') as w:
        params = w.getparams()
        frames = round(bars * 4 * 60.0 / bpm * params.framerate)
        if frames > params.nframes:
            sys.exit(f"{path} is shorter than {bars} bars at {bpm} BPM")
        data = w.readframes(frames)
    out = io.BytesIO()
    with wave.open(out, 'wb') as w:
        w.setparams(params._replace(nframes=frames))
        w.writeframes(data)
    return out.getvalue()

args = sys.argv[1:]
if not args or len(args) % 4:
    sys.exit(__doc__)

items = []
for i in range(0, len(args), 4):
    name, path, bars, bpm = args[i], args[i + 1], int(args[i + 2]), float(args[i + 3])
    items.append((name, bars * 4, trimmed_wav(path, bars, bpm)))

dest = os.path.join(os.path.dirname(__file__), '..', 'Source', 'DevBreaks.h')
with open(dest, 'w') as f:
    f.write('#pragma once\n// Generated by Tools/make_dev_breaks.py. Not in git; Debug builds only.\n\n')
    f.write('namespace DevBreaks\n{\n')
    for n, (_, _, data) in enumerate(items):
        f.write(f'    static const unsigned char data{n}[] = {{\n')
        for j in range(0, len(data), 24):
            f.write('        ' + ','.join(str(b) for b in data[j:j + 24]) + ',\n')
        f.write('    };\n\n')
    f.write('    struct Item { const char* name; double beats; const unsigned char* data; size_t size; };\n\n')
    f.write('    static const Item items[] = {\n')
    for n, (name, beats, _) in enumerate(items):
        f.write(f'        {{ "{name} (test)", {beats:.1f}, data{n}, sizeof (data{n}) }},\n')
    f.write('    };\n}\n')
print(f"wrote {os.path.normpath(dest)}")
